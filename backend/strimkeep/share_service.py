def install(store):
    """建表与轻量迁移：为 share_strms 补充整理证据列（幂等）。"""
    store.db.execute('''CREATE TABLE IF NOT EXISTS share_strms(
        id TEXT PRIMARY KEY, share_code TEXT NOT NULL, receive_code TEXT NOT NULL DEFAULT '',
        file_id TEXT NOT NULL, pickcode TEXT NOT NULL DEFAULT '', name TEXT NOT NULL,
        strm_path TEXT NOT NULL, token_hash TEXT NOT NULL,
        revoked INTEGER NOT NULL DEFAULT 0, created REAL NOT NULL)''')
    store.db.execute('''CREATE TABLE IF NOT EXISTS share_watchlist(
        share_code TEXT NOT NULL, receive_code TEXT NOT NULL DEFAULT '',
        last_checked REAL, created REAL NOT NULL,
        PRIMARY KEY(share_code))''')
    store.db.execute('''CREATE TABLE IF NOT EXISTS share_revocations(
        share_code TEXT NOT NULL, file_id TEXT NOT NULL, reason TEXT NOT NULL DEFAULT '',
        created REAL NOT NULL, PRIMARY KEY(share_code, file_id))''')
    store.db.execute('''CREATE TABLE IF NOT EXISTS share_wash_intents(
        id TEXT PRIMARY KEY, job_id INTEGER NOT NULL, payload TEXT NOT NULL)''')
    columns = {row[1] for row in store.db.execute('PRAGMA table_info(share_strms)')}
    for name, ddl in (('attachments', " TEXT NOT NULL DEFAULT '[]'"), ('media', ' TEXT'), ('facts', ' TEXT'), ('origin', ' TEXT'), ('size', ' REAL NOT NULL DEFAULT 0'), ('source_dirs', " TEXT NOT NULL DEFAULT ''"), ('source_layout', ' INTEGER NOT NULL DEFAULT 0')):
        if name not in columns:
            store.db.execute(f'ALTER TABLE share_strms ADD COLUMN {name}{ddl}')
    store.db.commit()


def directories(root):
    root = Path(root)
    pending, lib, unident = root / PENDING_NAME, root / LIB_NAME, root / UNIDENT_NAME
    for d in (pending, lib, unident):
        d.mkdir(parents=True, exist_ok=True)
    return pending, lib, unident


def share_is_dead(exc):
    """115 明确判定分享不可用：文件不存在，或分享已被取消（errno 4100010）。

    「分享已取消」返回的是 CLOUD_REJECTED 而不是 SHARE_NOT_FOUND，只认后者会让
    死分享永远留着：STRM 一直 404，媒体信息提取一直失败，日志里只有「暂时无法判定」。
    """
    if not isinstance(exc, CloudError):
        return False
    if exc.code == 'SHARE_NOT_FOUND':
        return True
    return exc.code == 'CLOUD_REJECTED' and '分享已取消' in str(exc)


def finish_share_wash(engine, intent):
    """Complete a published share replacement using its durable intent."""
    from urllib.parse import urlsplit
    store, root = engine.store, engine.root.resolve()
    payload = json.loads(intent['payload'])
    dest = root / payload['dest']
    if not dest.resolve().is_relative_to(root) or dest.is_symlink() or not dest.is_file():
        return False
    try:
        new_bytes = dest.read_bytes()
        if hashlib.sha256(new_bytes).hexdigest() != payload['digest'] or not share_play_path_matches(urlsplit(new_bytes.decode().strip()).path, intent['id']):
            return False
    except (OSError, UnicodeError, ValueError):
        return False
    with store.db:
        current = store.db.execute('SELECT strm_path,revoked FROM share_strms WHERE id=?', (intent['id'],)).fetchone()
        if not current or current['revoked'] or current['strm_path'] not in (payload['pending'],payload['dest']):
            return False
        store.db.execute('UPDATE share_strms SET strm_path=?,name=?,media=?,facts=?,origin=? WHERE id=?',
                         (payload['dest'],payload['name'],payload['media'],payload['facts'],payload['origin'],intent['id']))
        store.db.execute('INSERT OR IGNORE INTO strm_changes VALUES(?,?,?)', (intent['job_id'], 'updated', payload['dest']))
        if payload.get('item_id'):
            store.db.execute('INSERT OR IGNORE INTO strm_change_items VALUES(?,?,?,?)', (intent['job_id'],payload['item_id'],'updated',payload['dest']))
    unresolved = False
    for old in payload['retiring']:
        row = store.db.execute('SELECT strm_path,revoked FROM share_strms WHERE id=?', (old['id'],)).fetchone()
        if not row or row['revoked'] or row['strm_path'] != old['path']:
            continue
        old_path = root / old['path']
        if not old_path.resolve().is_relative_to(root) or old_path.is_symlink():
            store.event('share_wash', '旧分享 STRM 路径不安全，保留待核查。')
            unresolved = True
            continue
        if old['path'] != payload['dest']:
            try:
                if not old_path.exists() and old.get('unlink_started'):
                    with store.db:
                        store.db.execute('UPDATE share_strms SET revoked=1 WHERE id=? AND strm_path=?', (old['id'],old['path']))
                    continue
                content=old_path.read_bytes()
                if hashlib.sha256(content).hexdigest() != old['digest'] or not share_play_path_matches(urlsplit(content.decode().strip()).path, old['id']):
                    store.event('share_wash', '旧分享 STRM 内容已变化，保留待核查。')
                    unresolved = True
                    continue
                old['unlink_started'] = True
                with store.db:
                    store.db.execute('UPDATE share_wash_intents SET payload=? WHERE id=?', (json.dumps(payload,ensure_ascii=False), intent['id']))
                engine.outputs.unlink_recorded(intent['job_id'],old['path'],old_path,payload.get('item_id'))
            except (OSError, UnicodeError, ValueError):
                store.event('share_wash', '旧分享 STRM 无法核实，保留待核查。')
                unresolved = True
                continue
        if old['path'] == payload['dest']:
            with store.db:
                store.db.execute('INSERT OR IGNORE INTO strm_changes VALUES(?,?,?)', (intent['job_id'], 'replaced', payload['dest']))
                if payload.get('item_id'):
                    store.db.execute('INSERT OR IGNORE INTO strm_change_items VALUES(?,?,?,?)', (intent['job_id'],payload['item_id'],'replaced',payload['dest']))
        with store.db:
            store.db.execute('UPDATE share_strms SET revoked=1 WHERE id=? AND strm_path=?', (old['id'],old['path']))
        store.event('share_wash', '分享洗版：已发布新版并撤销旧入口 ' + old['id'])
    if unresolved:
        return False
    with store.db:
        store.db.execute('DELETE FROM share_wash_intents WHERE id=?', (intent['id'],))
    return True


def recover_share_washes(engine):
    for intent in engine.store.db.execute('SELECT * FROM share_wash_intents ORDER BY job_id').fetchall():
        if not finish_share_wash(engine, intent):
            engine.store.event('share_wash', '分享替换意图尚未确认，保留旧条目和记录。')


def _safe_component(value):
    text = str(value)
    if not text or text in ('.', '..') or '/' in text or '\\' in text or '\x00' in text:
        raise ValueError('分享内名称包含不安全字符，已停止。')
    return text


async def list_videos(cloud, secret, video_extensions=None):
    allowed = PLAYABLE if video_extensions is None else set(video_extensions)
    """遍历分享内容，返回视频文件（含分享内相对目录 path）。"""
    videos = []

    async def walk(cid, path):
        entries = await cloud.share_items(secret, cid)
        attachments = [{'id':v['id'],'name':v['name'],'size':v.get('size',0)} for v in entries if not v['is_dir'] and Path(v['name']).suffix.lower() not in allowed]
        for entry in entries:
            if entry['is_dir']:
                await walk(entry['id'], path + entry['name'] + '/')
            elif Path(entry['name']).suffix.lower() in allowed:
                video = {'id':entry['id'],'name':entry['name'],'size':entry.get('size',0),'path':path,'attachments':attachments}
                if entry.get('sha1'):
                    video['sha1'] = entry['sha1']
                videos.append(video)

    await walk('0', '')
    return videos


def generate(store, root, secret, videos, origin='web', settings_snapshot=None, allow_restore=False):
    settings_snapshot = settings_snapshot or share_effective_settings(store)
    """分享根目录平铺，子目录保留原有布局，不创建分享码目录。"""
    pending, _, _ = directories(root)
    created, skipped = [], []
    for video in videos:
        file_id = str(video.get('id', ''))
        name = str(video.get('name', ''))[:200]
        if not file_id or not name:
            continue
        _, organize_filter = filter_files([{'name':name,'size':video.get('size',0)}], settings_snapshot.get('organize', options(store.get('organize_config',{}))))
        reason = (organize_filter['examples'][0]['reason'] if organize_filter['excluded'] else '') or skip_reason({'name':name,'size':video.get('size',0)}, settings_snapshot['strm'])
        if reason:
            skipped.append({'name':name,'reason':reason})
            continue
        existing = store.db.execute('SELECT * FROM share_strms WHERE share_code=? AND file_id=? AND revoked=0',
                                    (secret['share_code'], file_id)).fetchone()
        if store.db.execute('SELECT 1 FROM share_revocations WHERE share_code=? AND file_id=?',
                            (secret['share_code'], file_id)).fetchone():
            skipped.append({'name': name, 'reason': '已主动撤销；如需恢复请到治理计划中执行恢复'})
            continue
        if existing:
            # A user must explicitly resubmit. Monitors and resumed tasks never
            # recreate a missing file the user may have intentionally removed.
            if not allow_restore:
                skipped.append({'name': name, 'reason': '已存在'})
                continue
            root_path = Path(root).resolve()
            old_relative = Path(existing['strm_path'])
            try:
                if old_relative.is_absolute() or not old_relative.parts or any(part in ('.', '..') for part in old_relative.parts):
                    raise ValueError('unsafe existing path')
                old_path = root_path / old_relative
                cursor = root_path
                for part in old_relative.parts:
                    cursor /= part
                    if cursor.is_symlink(): raise ValueError('symlink in existing path')
                try:
                    old_path.lstat()
                except FileNotFoundError:
                    pass
                else:
                    skipped.append({'name': name, 'reason': '已存在'})
                    continue
                old_size = float(existing['size'] or 0)
                new_size = float(video.get('size', 0) or 0)
                if (existing['name'] != name or existing['receive_code'] != secret.get('receive_code', '')
                        or (old_size and new_size != old_size)
                        or existing['token_hash'] != hashlib.sha256(b'').hexdigest()):
                    raise ValueError('original identity cannot be confirmed')
            except (OSError, ValueError, TypeError):
                skipped.append({'name': name, 'reason': '原记录或文件状态无法确认，未重建'})
                continue
            sid = existing['id']
        else:
            sid = secrets.token_hex(16)
        token = ''
        dir_parts = [_safe_component(p) for p in (video.get('path') or '').split('/') if p]
        share_dir = pending.joinpath(*dir_parts)
        share_dir.mkdir(parents=True, exist_ok=True)
        safe_name = _safe_component(name)
        strm_file = share_dir / (safe_name + '.strm')
        base = settings_snapshot.get('playback_base', store.get('playback_base') or '')
        content = share_play_url(base, sid, name).encode()
        # 不覆盖已有文件；不同分享可能包含同名视频。
        if not write_new(strm_file, content, root):
            short_name = safe_name.encode('utf-8')[:220].decode('utf-8', errors='ignore')
            strm_file = share_dir / (short_name + ' [' + sid[:12] + '].strm')
            if not write_new(strm_file, content, root):
                raise FileExistsError('分享 STRM 目标已存在，未覆盖。')
        rel = strm_file.relative_to(root).as_posix()
        try:
            with store.db:
                if existing:
                    changed = store.db.execute(
                        'UPDATE share_strms SET strm_path=?,source_dirs=?,source_layout=1,origin=? WHERE id=? AND revoked=0 AND strm_path=?',
                        (rel, json.dumps(dir_parts, ensure_ascii=False), origin, sid, existing['strm_path'])).rowcount
                    if changed != 1:
                        raise ValueError('原记录已变化，未重建')
                else:
                    store.db.execute(
                        'INSERT INTO share_strms(id,share_code,receive_code,file_id,pickcode,name,strm_path,token_hash,revoked,created,media,facts,origin,size,source_dirs,source_layout) '
                        'VALUES(?,?,?,?,?,?,?,?,0,?,NULL,NULL,?,?,?,1)',
                        (sid, secret['share_code'], secret.get('receive_code', ''), file_id, '', name, rel,
                         hashlib.sha256(token.encode()).hexdigest(), time.time(), origin, float(video.get('size', 0) or 0), json.dumps(dir_parts, ensure_ascii=False)))
        except Exception:
            # This path was created with write_new and is ours; a failed registry
            # update must not leave an unregistered active playback file.
            # 走 purge_strm：先登记再删，保持「删 STRM 必登记」的全局约定。
            try:
                purge_strm(strm_file, root, store=store)
            except (OSError, RuntimeError):
                pass
            raise
        with store.db:
            store.db.execute('UPDATE share_strms SET attachments=? WHERE id=?', (json.dumps(video.get('attachments', []),ensure_ascii=False),sid))
        created.append({'id': sid, 'name': name, 'strm_path': rel})
    with store.db:
        store.db.execute('INSERT OR IGNORE INTO share_watchlist(share_code,receive_code,created) VALUES(?,?,?)',
                         (secret['share_code'], secret.get('receive_code', ''), time.time()))
    return {'created': created, 'skipped': skipped}


def enqueue_organize(engine, origin='web', secret=None, channel_claim=None, generate_only=False, pending_only=False):
    """把整理放入持久化 FIFO（U03）。secret 存在时任务会先补齐该分享的待整理。"""
    store = engine.store
    inherited = share_effective_settings(store)
    config = {'job_kind':'share_organize','origin':origin,'notify_emby':inherited['notify_emby'],
              'organize_options':inherited['organize'],'upgrade_policy':inherited['upgrade_policy'],
              'strm_options':inherited['strm'],'playback_base':inherited['playback_base'],'shared_version':inherited['version']}
    if generate_only: config['generate_only'] = True
    if pending_only: config['pending_only'] = True
    now = time.time()
    with store.transaction():
        jid = store.jobs.create(json.dumps(config, ensure_ascii=False))
        if secret:
            store.db.execute('INSERT OR REPLACE INTO settings VALUES(?,?)',
                             ('share-secret:' + str(jid),
                              store.crypto.encrypt(json.dumps(secret, ensure_ascii=False).encode()).decode()))
        if channel_claim:
            name, message_id = channel_claim
            changed = store.db.execute(
                'UPDATE channel_shares SET job_id=? WHERE share_code=? AND name=? AND message_id=? AND job_id IS NULL',
                (jid, secret['share_code'], name, message_id)).rowcount
            if changed != 1:
                raise ValueError('频道分享认领状态已变化，请重新核对。')
    store.event('share', f'分享 STRM 整理任务 {jid} 已入队（来源 {origin}）。')
    return jid


def enqueue_pending_organize(engine, origin='web'):
    """合并尚未开始的待整理任务；运行中的任务需要后续任务接住新文件。"""
    for row in engine.store.db.execute("SELECT id,config FROM organize_jobs WHERE state='queued' ORDER BY id"):
        try:
            config=json.loads(row['config'] or '{}')
        except (TypeError, ValueError):
            continue
        if config.get('job_kind')=='share_organize' and config.get('pending_only'):
            return row['id']
    return enqueue_organize(engine, origin=origin, pending_only=True)


async def run_organize(engine, job_id, config):
    """share_organize 任务体：可重入，进度以 share_strms 行为准。"""
    from .core import UncertainState
    store, root = engine.store, engine.root
    resumed_manifest = bool(engine.job(job_id)['manifest'])
    install(store)
    recover_share_washes(engine)
    settings = config.get('organize_options') or {**store.get('share_settings', {}), **options(store.get('organize_config', {}))}
    settings = {**settings, 'notify_emby':config.get('notify_emby',settings.get('notify_emby',True))}
    strm_rules = config.get('strm_options') or shared_settings(store)['strm']
    pending, lib, unident = directories(root)
    policy = public_policy(config.get('upgrade_policy', store.get('upgrade_policy')))
    ffprobe_on = settings.get('ffprobe_enabled', True)
    wash_on = settings.get('wash_enabled', True)

    # 阶段 A：TG 整链接任务 → 先补齐该分享的待整理（U03/U04）。
    secret = store.get('share-secret:' + str(job_id))
    if secret:
        engine.update_job(job_id, stage='读取分享内容并生成待整理 STRM')
        videos = await list_videos(engine.cloud, secret, strm_rules['video_extensions'])
        if not videos:
            engine.update_job(job_id, state='completed', stage='分享整理结束', manifest=1, message='未发现符合当前视频扩展名的文件，其他格式已按规则跳过。')
            return
        allow_restore = config.get('origin') == 'telegram' and not resumed_manifest and not config.get('share_generation_started')
        if not config.get('share_generation_started'):
            config['share_generation_started'] = True
            engine.update_job(job_id, config=json.dumps(config, ensure_ascii=False))
        result = generate(store, root, secret, videos, origin=config.get('origin', 'telegram'), settings_snapshot={'strm':strm_rules,'organize':settings,'playback_base':config.get('playback_base',store.get('playback_base') or '')}, allow_restore=allow_restore)
        if config.get('generate_only'):
            engine.update_job(job_id, state='completed', stage='分享 STRM 已生成', manifest=1,
                              message='已生成 %d 个待整理 STRM；自动整理已关闭。' % len(result['created']))
            return
        pending_for_share = store.db.execute("SELECT 1 FROM share_strms WHERE revoked=0 AND share_code=? AND strm_path LIKE ? LIMIT 1", (secret['share_code'], PENDING_NAME + '/%')).fetchone()
        if not result['created'] and not pending_for_share:
            engine.update_job(job_id, state='completed', stage='分享整理结束', manifest=1,
                              message='这些文件之前已经生成过 STRM，没有新增。')
            return

    # 阶段 B：整理待整理目录（旧平铺布局与新镜像布局都识别）。
    if not store.get('tmdb_key'):
        raise UncertainState('请先配置 TMDB API Key，再整理分享 STRM。')
    rows = store.db.execute(
        "SELECT * FROM share_strms WHERE revoked=0 AND strm_path LIKE ? ORDER BY created, id",
        (PENDING_NAME + '/%',)).fetchall()
    # Capture original source membership before any successful item moves.
    # A durable marker makes a restarted or interrupted batch conservative:
    # old successes cannot be inferred from the remaining pending rows.
    layouts, layout_rows, uncertain_layouts = {}, {}, set()
    for source_row in rows:
        layout = _share_work_layout(source_row)
        layouts[source_row['id']] = layout
        if layout:
            layout_rows.setdefault(layout[0], []).append(source_row)
    with store.db:
        for key in layout_rows:
            marker = _share_layout_marker(key)
            if resumed_manifest or store.meta(marker) or store.meta(_share_layout_success(key)):
                uncertain_layouts.add(key)
            store.db.execute('INSERT OR REPLACE INTO meta VALUES(?,?)', (marker, str(job_id)))
    deferred_unidentified = []
    item_by_share = {}
    used_file_ids = set()
    store.jobs.clear_items(job_id)
    with store.db:
        for row in rows:
            # organize_items has UNIQUE(job_id,file_id); a source file can
            # legitimately appear under multiple distinct share records.
            item_file_id = row['file_id']
            if item_file_id in used_file_ids:
                item_file_id = 'share:' + row['id']
            used_file_ids.add(item_file_id)
            item_by_share[row['id']] = store.jobs.insert_item(
                job_id, item_file_id,
                {'id': row['file_id'], 'name': row['name'], 'size': row['size'] or 0,
                 'share_record_id': row['id'], 'source_path': row['strm_path']},
                state='planned')
        store.jobs.set_manifest(job_id)
    if not rows:
        engine.update_job(job_id, state='completed', stage='分享整理结束', manifest=1,
                          message='没有待整理的分享 STRM。')
        return

    # 批量识别预取：与整理页的「批量识别预取」同一开关，只并发读，不改变任何写顺序。
    if settings.get('identify_prefetch', True) and len(rows) > 1:
        hints, seen = [], set()
        for row in rows:
            try:
                hint = share_recognition_hint(row)
            except NeedsReview:
                continue
            key = (hint['media_type'], hint['query'], hint['year'] or 0)
            if key not in seen:
                seen.add(key)
                hints.append(hint)
        limit = max(1, min(4, int(settings.get('probe_concurrency') or 2)))
        semaphore = asyncio.Semaphore(limit)

        async def warm(hint):
            async with semaphore:
                engine.boundary(job_id)
                params = {'query': hint['query'], 'include_adult': 'false'}
                if hint['year'] and hint['media_type'] != 'tv':
                    params['year'] = hint['year']
                try:
                    await engine.tmdb('search/' + hint['media_type'], params)
                except asyncio.CancelledError:
                    raise
                except Exception:
                    pass

        tasks = [asyncio.create_task(warm(hint)) for hint in hints]
        try:
            await asyncio.gather(*tasks)
        except BaseException:
            for task in tasks:
                task.cancel()
            await asyncio.gather(*tasks, return_exceptions=True)
            raise

    groups, membership, sent = {}, {}, set()
    for candidate in rows:
        try:
            h = share_recognition_hint(candidate)
            title = normal(h.get('query') or '')
            key = ('tv',title,h.get('year'),h['season']) if h['media_type']=='tv' and title else ('file',candidate['id'])
        except NeedsReview:
            key = ('file',candidate['id'])
        groups.setdefault(key,[]).append(item_by_share[candidate['id']])
        membership[candidate['id']] = key

    async def report_finished(key):
        if key in sent:return
        ids=groups[key];marks=','.join('?' for _ in ids)
        current=store.db.execute(f'SELECT * FROM organize_items WHERE job_id=? AND id IN ({marks}) ORDER BY id',(job_id,*ids)).fetchall()
        if len(current)!=len(ids) or any(r['state'] not in ('done','skipped','review','pending','recycled') for r in current):return
        sent.add(key)
        successes=[r for r in current if r['state']=='done']
        confirmed={}
        for r in successes:
            plan=json.loads(r['plan'] or '{}');hint=plan.get('hint',{});details=plan.get('details',{})
            identity=(hint.get('media_type'),details.get('id'),hint.get('season')) if key[0]=='tv' and details.get('id') else ('file',r['id'])
            confirmed.setdefault(identity,[]).append((r,plan))
        for subset in confirmed.values():
            if len(ids)==1:
                r,plan=subset[0];suffix=plan['relative_path']+':'+str(r['id'])
            else:
                suffix='group:'+','.join(str(r['id']) for r,_ in subset)
            other=[r for r in current if r['state']!='done']
            acc={'details':subset[0][1].get('details',{}), 'shared':True,
                 'episodes':[(json.loads(r['original']),plan) for r,plan in subset],
                 'items':[(r['id'],plan) for r,plan in subset],
                 'other_items':[(json.loads(r['original']),json.loads(r['plan'] or '{}'),r['state'],r['step']) for r in other] if len(confirmed)==1 else [],
                 'unassigned':len(other) if len(confirmed)!=1 else 0,
                 'unfinished':len(other)}
            engine.queue_show_notice(job_id,suffix,acc)
        await asyncio.sleep(0)

    moved, unident_count, skipped_count = 0, 0, 0
    # Only share identity within this batch when the search returned one
    # candidate and year evidence does not depend on a specific episode.
    identity_cache = {}
    # One authoritative share listing per share per job. User-supplied metadata
    # is never trusted as cache proof; changed/unavailable shares skip the cache.
    share_proofs, pending_media = {}, []

    async def share_proof(row, refresh=False):
        key = (row['share_code'], row['receive_code'])
        if refresh or key not in share_proofs:
            try:
                files = await list_videos(engine.cloud, {'share_code': key[0], 'receive_code': key[1]},
                                          strm_rules['video_extensions'])
                share_proofs[key] = {str(f['id']): f for f in files}
            except asyncio.CancelledError:
                raise
            except CloudError as exc:
                if fatal(exc):
                    raise
                share_proofs[key] = {}
            except Exception:
                share_proofs[key] = {}
        file = share_proofs[key].get(str(row['file_id']))
        if not file or file.get('name') != row['name']:
            return None
        size = row['size'] or 0
        if not isinstance(size, (int, float)) or int(size) != size or int(size) != file.get('size'):
            return None
        source = {'id': str(row['file_id']), 'sha1': file.get('sha1', ''), 'size': int(size)}
        return source if engine.measurements.fingerprint(source) else None

    reasons = []
    for row in rows:
        try:
            engine.boundary(job_id)
            item = store.db.execute('SELECT id FROM organize_items WHERE id=? AND job_id=?', (item_by_share[row['id']], job_id)).fetchone()
            pending_file = root / row['strm_path']
            if not pending_file.is_file():
                # 待整理 STRM 已不在我方目录：按用户撤回处理，不猜测。
                if item:
                    engine.update_item(item['id'], state='skipped', step='待整理 STRM 已不存在', message='文件已被移除，保持登记不变。')
                skipped_count += 1
                continue
            accepted, report = filter_files([dict(row)], settings)
            generation_skip = skip_reason({'name':row['name'],'size':row['size']}, strm_rules)
            if report['excluded'] or generation_skip:
                reason = generation_skip or report['examples'][0]['reason']
                if item:engine.update_item(item['id'], state='skipped', step='按整理规则跳过', message=reason)
                reasons.append(row['name'][:60] + '：' + reason)
                skipped_count += 1
                continue
            if config.get('origin') == 'schedule':
                held = store.meta('share-unident-hold:' + row['id'])
                if held:
                    try:
                        saved = json.loads(held)
                        # Deferred group placement can change as other
                        # episodes finish. Suppress a retry only when every
                        # possible destination remains occupied.
                        if saved.get('deferred_layout'):
                            options = list(_unidentified_targets(unident, row, (Path(row['strm_path']).name,)))
                            layout = layouts.get(row['id'])
                            if layout:
                                options.extend(_unidentified_targets(unident, row, layout[1]))
                            if any(not (p.exists() or p.is_symlink()) for p in options):
                                raise ValueError('a destination became available')
                        target_path = saved.get('target_path')
                        if target_path is None:
                            # Legacy holds used the original mirrored path.
                            target = unident / Path(row['strm_path']).relative_to(PENDING_NAME)
                        else:
                            rel = Path(target_path)
                            if rel.is_absolute() or not rel.parts:
                                raise ValueError('invalid hold target')
                            target = unident.joinpath(*(_safe_component(part) for part in rel.parts))
                            natural = _unidentified_targets(unident, row)[0]
                            # If the original name becomes free, the fallback
                            # collision no longer blocks this item.
                            if not saved.get('deferred_layout') and target != natural and not (natural.exists() or natural.is_symlink()):
                                raise ValueError('original name is available')
                        signature = _share_hold_signature(row, pending_file, target, settings, store.get('tmdb_key'))
                        if signature and saved.get('signature') == signature and time.time() - saved.get('at', 0) < 21600:
                            if item:
                                engine.update_item(item['id'], state='skipped', step='同名未识别文件等待处理',
                                                   message='识别条件和冲突文件未变化，定时任务暂缓重试；手动整理可立即重试。')
                            skipped_count += 1
                            continue
                    except (ValueError, TypeError, OSError):
                        pass
            stem = Path(row['name']).stem
            try:
                hint = share_recognition_hint(row)
                identity_key = (hint['media_type'], normal(hint['query']), hint.get('year'),
                                hint.get('season'), hint.get('tmdb_id'))
                cached_identity = identity_cache.get(identity_key)
                if cached_identity:
                    details, evidence = copy.deepcopy(cached_identity)
                    hint['tmdb_attempt'] = evidence
                else:
                    original_query, original_season = hint['query'], hint.get('season')
                    details = await engine.identify(hint)
                    attempts = hint.get('tmdb_attempt') or []
                    searches = [a for a in attempts if a.get('endpoint') == 'search/' + hint['media_type'] and a.get('variant') == 'title']
                    first_year = str(details.get('first_air_date') or details.get('release_date') or '')[:4]
                    if (hint['query'] == original_query and hint.get('season') == original_season and
                            (hint.get('tmdb_id') or (len(searches) == 1 and searches[0].get('candidates') == 1)) and
                            (not hint.get('year') or str(hint['year']) == first_year)):
                        identity_cache[identity_key] = (copy.deepcopy(details), copy.deepcopy(attempts))
                episodes = []
                if hint['media_type'] == 'tv':
                    for number in range(hint['episode'], hint['end_episode'] + 1):
                        episode = await engine.tmdb(f"tv/{details['id']}/season/{hint['season']}/episode/{number}")
                        if episode.get('season_number') != hint['season'] or episode.get('episode_number') != number:
                            raise NeedsReview('TMDB 季集映射不匹配。')
                        episodes.append(episode)
                media = None
                if ffprobe_on:
                    source, account = None, None
                    try:
                        source = await share_proof(row)
                        cookie = store.get('cookie') or ''
                        account = engine.index.account(config) if source and re.search(r'(?:^|;\s*)UID=\d+', cookie) else None
                        if account:
                            sha, size = engine.measurements.fingerprint(source)
                            cached = store.db.execute(
                                'SELECT media FROM media_by_sha WHERE account_id=? AND sha1=? AND size=?',
                                (account, sha, size)).fetchone()
                            if cached:
                                candidate = json.loads(cached['media'])
                                if engine.measurements.sufficient(candidate, policy):
                                    media = candidate
                                    store.event('share_organize', '分享媒体信息命中已核实的内容缓存。')
                    except asyncio.CancelledError:
                        raise
                    except CloudError as exc:
                        if fatal(exc):
                            raise
                        source, account = None, None
                    except Exception:
                        source, account = None, None
                    if media is None:
                        try:
                            ua = PROBE_UA
                            probe_url, probe_headers = await engine.cloud.share_url_download(
                                row['file_id'], row['share_code'], row['receive_code'], ua)
                            media = await engine.probe(probe_url, {**probe_headers, 'User-Agent': ua})
                            if source and account and engine.measurements.sufficient(media):
                                pending_media.append((row, source, account, media, stem))
                        except CloudError as exc:
                            if fatal(exc):
                                raise
                            media = None
                        except Exception:
                            media = None
                if media is None:
                    media = media_from_filename(stem)
                # 以 .mkv 收尾让 naming 只追加一次后缀；技术字段解析仍读原始主干。
                titles = await title_options(engine, hint, details, settings)
                _, target_name, _, _ = naming(hint, details, episodes, media, stem + Path(row['name']).suffix, policy=policy, options=titles)
                target_stem = Path(target_name).stem if settings.get('rename_enabled', True) else component(stem, 180)
                parts, _, _ = work_parts(hint, details, titles)
            except CloudError as exc:
                if exc.code in ('LOGIN_REQUIRED', 'LOGIN_INVALID', 'RATE_LIMITED', 'TMDB_UNAVAILABLE', 'CLOUD_UNAVAILABLE'):
                    raise  # Transient service failures are not recognition failures.
                deferred_unidentified.append((row, item, str(exc) or type(exc).__name__, False, None))
                if len(reasons) < 3:
                    reasons.append(f'{row["name"][:38]}：{str(exc)[:140]}')
                unident_count += 1
                continue
            except Exception as exc:
                reason = (str(exc) or type(exc).__name__)[:140]
                deferred_unidentified.append((row, item, reason, isinstance(exc, NeedsReview), settings))
                if len(reasons) < 3:
                    reasons.append(f'{row["name"][:38]}：{reason}')
                store.event('share_organize', f'分享 STRM 未识别：{row["name"][:60]}（{reason}）')
                unident_count += 1
                continue

            stack = [(lib, [])]; found = []
            while stack:
                directory, relative = stack.pop()
                if not directory.is_dir() or directory.is_symlink():continue
                for sibling in directory.iterdir():
                    if not sibling.is_dir() or sibling.is_symlink():continue
                    tag = re.search(r'\{tmdb-(\d+)\}', sibling.name)
                    if tag:
                        has_seasons = any(v.is_dir() and re.match(r'(?i)^Season\s+\d+', v.name) for v in sibling.iterdir())
                        if int(tag[1]) == int(details['id']) and has_seasons == (hint['media_type'] == 'tv'):
                            found.append((sibling, [*relative,sibling.name]))
                    elif len(relative) < 3:stack.append((sibling,[*relative,sibling.name]))
            if len(found) == 1:
                existing_dir, existing_parts = found[0]
                parts = [*existing_parts, *parts[-1:]] if hint['media_type'] == 'tv' else existing_parts
                if settings.get('rename_enabled', True) and settings.get('keep_existing_names', True):
                    from .organize_options import file_title
                    examples = sorted(v for v in existing_dir.rglob('*.strm') if not v.is_symlink())
                    old_title = next((file_title(v.name) for v in examples if file_title(v.name)), '')
                    new_title = file_title(target_stem)
                    if old_title and new_title:target_stem = old_title + target_stem[len(new_title):]
            org_dir = lib.joinpath(*parts)
            dest = org_dir / (target_stem + '.strm')
            dest_rel = dest.relative_to(root).as_posix()
            new_facts = facts(stem + '.mkv', media, row['size'] or 0)
            retiring = []
            verdict = _wash(engine, job_id, row, org_dir, dest, target_stem, hint,
                            new_facts, policy, wash_on, retiring)
            if verdict == 'pending':
                deferred_unidentified.append((row, item, '按继承的冲突策略保留旧版，新副本转待处理。', False, None))
                unident_count += 1
                continue
            if verdict == 'hold':
                if item:engine.update_item(item['id'],state='skipped',step='按继承规则原位跳过',message='保留旧版及待整理的新 STRM，不执行洗版。')
                skipped_count += 1
                continue
            if verdict == 'skip':
                layout = layouts.get(row['id'])
                if layout: store.set_meta(_share_layout_success(layout[0]), 1)
                pending_file.unlink(missing_ok=True)
                with store.db:
                    store.db.execute('DELETE FROM share_strms WHERE id=?', (row['id'],))
                if item:
                    engine.update_item(item['id'], state='skipped', step='已有同集或同名条目，保留已有',
                                       message=verdict_reason(verdict, target_stem))
                skipped_count += 1
                continue
            org_dir.mkdir(parents=True, exist_ok=True)
            # 「新增」= 目标路径既没有文件，也没有任何历史登记（含已撤销）。洗版重发
            # 同一季时目标路径早就登记过，不算新增，通知里不再重复列这几十集。
            created = bool(not dest.is_file() and not store.db.execute(
                'SELECT 1 FROM share_strms WHERE strm_path=?', (dest_rel,)).fetchone())
            if not refresh_share_address(store, row, pending_file, config.get('playback_base',store.get('playback_base') or ''), dest.stem + Path(row['name']).suffix):
                raise UncertainState('分享 STRM 内容无法确认，保留原文件及旧版。')
            pending_bytes = pending_file.read_bytes()
            old_records = []
            for old in retiring:
                old_path = root / old['strm_path']
                from urllib.parse import urlsplit
                try:
                    if not old_path.resolve().is_relative_to(root.resolve()) or old_path.is_symlink() or old_path.stat().st_size > 4096:
                        raise ValueError('unsafe')
                    data = old_path.read_bytes()
                    if not share_play_path_matches(urlsplit(data.decode().strip()).path, old['id']):
                        raise ValueError('ownership')
                    old_records.append({'id': old['id'], 'path': old['strm_path'], 'digest': hashlib.sha256(data).hexdigest()})
                except (OSError, UnicodeError, ValueError):
                    if old['strm_path'] == dest_rel:
                        raise UncertainState('同名旧分享 STRM 归属无法确认，禁止覆盖。')
                    store.event('share_wash','旧分享 STRM 归属无法确认，保留待核查。')
            if dest.exists() and not any(old['path'] == dest_rel for old in old_records):
                raise UncertainState('新分享 STRM 目标已存在且归属未确认，禁止覆盖。')
            intent_payload = {'pending':row['strm_path'], 'dest':dest_rel, 'digest':hashlib.sha256(pending_bytes).hexdigest(), 'item_id':item['id'] if item else None,
                              'name':target_stem, 'media':json.dumps(media,ensure_ascii=False), 'facts':json.dumps(new_facts,ensure_ascii=False),
                              'origin':config.get('origin','web'), 'retiring':old_records}
            with store.db:
                store.db.execute('INSERT OR REPLACE INTO share_wash_intents(id,job_id,payload) VALUES(?,?,?)', (row['id'],job_id,json.dumps(intent_payload,ensure_ascii=False)))
            # Retain proof that this original work has an accepted member even
            # if this task is interrupted after publishing.
            layout = layouts.get(row['id'])
            if layout: store.set_meta(_share_layout_success(layout[0]), 1)
            os.replace(pending_file, dest)
            if strm_rules.get('cleanup_empty',True):await cleanup_empty_pending_async(pending_file.parent,pending)
            await copy_share_metadata(engine, job_id, row, dest, strm_rules)
            metadata_files = []
            try:
                metadata_files = await write_sidecars(engine, dest, {'hint': hint, 'details': details, 'episodes': episodes}, strm_rules)
            except Exception as exc:
                store.event('share_organize', '分享 NFO/海报生成失败：%s' % str(exc)[:80])
            intent = store.db.execute('SELECT * FROM share_wash_intents WHERE id=?', (row['id'],)).fetchone()
            if not finish_share_wash(engine, intent):
                raise UncertainState('新分享 STRM 发布结果未确认，保留旧版与恢复记录。')
            if item:
                engine.update_item(item['id'], plan={
                    'relative_path': dest_rel, 'playback_id': 'share/' + row['id'], 'target_stem': target_stem, 'hint': hint,
                    'details': details, 'media': media, 'parts': parts, 'metadata_files': metadata_files,
                    'share_wash_replaced': bool(old_records), 'strm_created': created,
                    'source': {'id': row['file_id'], 'name': row['name'], 'size': row['size'] or 0},
                }, state='done', step='已入库分享影视库')
            moved += 1

        finally:
            try:
                await report_finished(membership[row['id']])
            except Exception as exc:
                store.event('share_organize', f'任务 {job_id}：分组通知未完成（{type(exc).__name__}）。')

    # Outcomes are now known for the full initial manifest. Only an entirely
    # failed, complete work group may keep its work folder. Everything else
    # is an individual loose file, never a move of its parent directory.
    failures = {row['id'] for row, _, _, _, _ in deferred_unidentified}
    preserve = set()
    for key, members in layout_rows.items():
        if key in uncertain_layouts or not all(row['id'] in failures for row in members):
            continue
        allowed = {row['strm_path'] for row in members}
        # Registered entries from another share may share this physical work
        # directory. They are known, but belong to their own outcome group.
        source_dir = root / PENDING_NAME
        layout_version = int(members[0]['source_layout'] or 0)
        if layout_version == 0:
            source_dir = source_dir / key[0]
        source_dir = source_dir.joinpath(*key[1])
        try:
            if source_dir.is_symlink() or not source_dir.is_dir():
                continue
            # A file not in the original manifest means the group is incomplete;
            # no assumption is made about its eligibility or ownership.
            observed = {p.relative_to(root).as_posix() for p in source_dir.rglob('*.strm') if p.is_file()}
            known = {r['strm_path'] for r in rows}
            if not allowed.issubset(observed) or not observed.issubset(known):
                continue
        except OSError:
            continue
        preserve.add(key)
    for row, item, reason, deterministic, extra_settings in deferred_unidentified:
        engine.boundary(job_id)
        layout = layouts.get(row['id'])
        relative = layout[1] if layout and layout[0] in preserve else (Path(row['strm_path']).name,)
        await _to_unident(engine, job_id, row, item, reason, deterministic=deterministic,
                          settings=extra_settings, target_parts=relative)
        try:
            await report_finished(membership[row['id']])
        except Exception as exc:
            store.event('share_organize', f'任务 {job_id}：分组通知未完成（{type(exc).__name__}）。')
    with store.db:
        for key in layout_rows:
            store.db.execute('DELETE FROM meta WHERE key=? AND value=?', (_share_layout_marker(key), str(job_id)))

    # Re-read each share once after probing; changed or inaccessible sources do
    # not seed content caches. This avoids trusting stale or submitted SHA1s.
    refreshed = set()
    for row, source, account, media, raw_name in pending_media:
        key = (row['share_code'], row['receive_code'])
        try:
            verified = await share_proof(row, refresh=key not in refreshed)
            refreshed.add(key)
            if verified and engine.measurements.fingerprint(verified) == engine.measurements.fingerprint(source):
                engine.measurements.put(account, verified, media, raw_name)
        except asyncio.CancelledError:
            raise
        except Exception:
            pass  # Cache persistence must not turn successful output into failure.

    message_parts = [f'入库 {moved}', f'未识别 {unident_count}', f'跳过 {skipped_count}']
    if reasons:
        message_parts.extend(reasons)
    notify_state = 'not_needed'
    if moved and settings.get('notify_emby', True):
        connection = engine.emby.connection()
        if not connection:
            notify_state = 'failed'
        else:
            # 与整理/同步走同一条交付通道：只通知本批真实变化的路径，由 EmbyDelivery
            # 负责提交、逐条核对与重试。不再直接请求全库 /Library/Refresh ——
            # 那在大库上是一次全量重扫，而且没有入库确认。
            try:
                if engine.emby.targets(job_id):
                    engine.emby.enqueue(job_id)
                    notify_state = 'retrying'
                else:
                    notify_state = 'not_needed'
                    store.event('emby', f'任务 {job_id}：本批没有可通知的路径变更，未请求 Emby 扫描。')
            except Exception as exc:
                notify_state = 'failed'
                store.event('emby', f'任务 {job_id}：路径通知入队失败（{type(exc).__name__}）。')
    # 未识别是正常结果（STRM 已放进未识别目录等人工处理），不该让任务变「部分未完成」；
    # 通知失败有独立的 notify_state，也不该拖累任务状态。和网盘库口径保持一致。
    engine.update_job(job_id, state='completed',
                      stage='分享整理结束', notify_state=notify_state,
                      message='；'.join(message_parts) + '。')
    # 媒体信息 sidecar 由 native_media_info 的定时补扫负责（只处理已入库且缺 sidecar 的条目），
    # 这里不再重复入队：交付通道已经把本批路径交给 EmbyDelivery。


def verdict_reason(verdict, target_stem):
    if verdict == 'skip':
        return '同作品同集已有条目，或证据不足以淘汰旧条目：保留已有，放弃新条目。'
    return ''


def _share_hold_signature(row, pending_file, target, settings, tmdb_key):
    try:
        source_stat, target_stat = pending_file.stat(), target.stat()
    except OSError:
        return None
    evidence = [row['id'], row['name'], row['strm_path'], source_stat.st_size, source_stat.st_mtime_ns,
                target_stat.st_size, target_stat.st_mtime_ns, settings, tmdb_key or '', 'v1']
    return hashlib.sha256(json.dumps(evidence, ensure_ascii=False, sort_keys=True, default=str).encode()).hexdigest()


def _share_source_dirs(row):
    """Validated original directories; never treat a share code as a title."""
    path = Path(row['strm_path'])
    parts = path.parts
    if path.is_absolute() or len(parts) < 2 or parts[0] != PENDING_NAME:
        return None
    if any(part in ('.', '..') for part in parts):
        return None
    keys = row.keys()
    if 'source_layout' in keys and row['source_layout'] == 1:
        try:
            dirs = json.loads(row['source_dirs'])
            if not isinstance(dirs, list) or any(not isinstance(v, str) or _safe_component(v) != v for v in dirs):
                return None
        except (ValueError, TypeError):
            return None
        # Verify the registry still matches the actual pending directory.
        return tuple(dirs) if tuple(parts[1:-1]) == tuple(dirs) else None
    if len(parts) >= 3 and parts[1] == str(row['share_code']):
        return tuple(parts[2:-1])
    return () if len(parts) == 2 else None


def _share_work_layout(row):
    """Return trustworthy source group and its work-relative destination."""
    from .media import SEASON_DIR
    path = Path(row['strm_path'])
    parts = path.parts
    code = str(row['share_code'])
    # Old records lack original group evidence: do not infer completeness.
    if 'source_layout' not in row.keys() or row['source_layout'] != 1:
        return None
    dirs = _share_source_dirs(row)
    if not dirs:
        return None
    index = len(dirs) - 1
    if SEASON_DIR.match(dirs[index]):
        index -= 1
    if index < 0:
        return None
    work = dirs[index].strip()
    # Classification directories are not works, even if they contain just one
    # unmatched file in this batch. Unknown groupings stay loose.
    from .media import folder_context
    work_context = folder_context(work)
    if _is_share_category(work) or (work_context and _is_share_category(work_context.get('title'))):
        return None
    if not normal(work):
        return None
    return (code, tuple(dirs[:index + 1])), tuple(dirs[index:]) + (parts[-1],)


def _share_layout_marker(key):
    return 'share-layout-incomplete:' + hashlib.sha256(json.dumps(key, ensure_ascii=False).encode()).hexdigest()


def _share_layout_success(key):
    return 'share-layout-success:' + hashlib.sha256(json.dumps(key, ensure_ascii=False).encode()).hexdigest()


def _unidentified_targets(unident, row, target_parts=None):
    """Keep original folders, remove only the generated share-code directory."""
    relative = Path(row['strm_path']).relative_to(PENDING_NAME)
    parts = relative.parts if target_parts is None else target_parts
    if target_parts is None and len(parts) > 1 and parts[0] == str(row['share_code']):
        parts = parts[1:]
    parts = tuple(_safe_component(part) for part in parts)
    if not parts:
        raise ValueError('missing pending filename')
    natural = unident.joinpath(*parts)
    name = natural.name
    suffix = ' [' + hashlib.sha256(str(row['id']).encode()).hexdigest()[:16] + '].strm'
    stem = name[:-5] if name.lower().endswith('.strm') else name
    short_stem = stem.encode('utf-8')[:255 - len(suffix.encode('utf-8'))].decode('utf-8', errors='ignore')
    return natural, natural.with_name(short_stem + suffix)


def _verified_share_strm(root, relative, share_id):
    """Return an owned regular STRM only if its path and embedded ID agree."""
    from urllib.parse import urlsplit
    root = Path(root).resolve()
    rel = Path(relative)
    if rel.is_absolute() or not rel.parts or any(part in ('.', '..') for part in rel.parts):
        return None
    path = root / rel
    try:
        cursor = root
        for part in rel.parts:
            cursor = cursor / part
            if cursor.is_symlink():
                return None
        if not path.resolve().is_relative_to(root) or not path.is_file() or path.stat().st_size > 4096:
            return None
        content = path.read_text(encoding='utf-8').strip()
        if not share_play_path_matches(urlsplit(content).path, str(share_id)):
            return None
        return path
    except (OSError, UnicodeError, ValueError):
        return None


async def _to_unident(engine, job_id, row, item, reason, deterministic=False, settings=None, target_parts=None):
    """Move each unmatched STRM while preserving its original work folders."""
    store, root = engine.store, engine.root
    _, _, unident = directories(root)
    pending_file = root / row['strm_path']
    targets = _unidentified_targets(unident, row, target_parts)
    target_dir = targets[0]
    moved = False
    try:
        current = store.db.execute('SELECT strm_path, revoked FROM share_strms WHERE id=?', (row['id'],)).fetchone()
        if not current or current['revoked'] or current['strm_path'] != row['strm_path'] or not _verified_share_strm(root, row['strm_path'], row['id']):
            raise OSError('unverified source')
        target_dir.parent.mkdir(parents=True, exist_ok=True)
        for target_dir in targets:
            try:
                # link() is atomic and never replaces an existing entry.
                os.link(pending_file, target_dir)
                break
            except FileExistsError:
                if target_dir == targets[-1]:
                    raise
        with store.db:
            # STRM 已移进未识别目录：这个入口不再有效，必须撤销登记。
            # 否则台账会留下「有登记、磁盘没文件」的悬空记录——现场 4 条
            # （05/06/27/28）就是这么来的：用户在未识别目录删掉 STRM 后台账还挂着。
            store.db.execute('UPDATE share_strms SET strm_path=?, revoked=1 WHERE id=?',
                             (target_dir.relative_to(root).as_posix(), row['id']))
        pending_file.unlink()
        moved = True
    except OSError as exc:
        detail = '待确认目录已有同名文件，原文件已保留' if isinstance(exc, FileExistsError) else '移动待确认目录失败，原文件已保留'
        if isinstance(exc, FileExistsError) and deterministic:
            signature = _share_hold_signature(row, pending_file, target_dir, settings or {}, store.get('tmdb_key'))
            if signature:
                with store.db:
                    store.db.execute('INSERT OR REPLACE INTO meta VALUES(?,?)',
                                     ('share-unident-hold:' + row['id'], json.dumps({'signature': signature, 'at': time.time(), 'target_path': target_dir.relative_to(unident).as_posix(), 'deferred_layout': target_parts is not None})))
        if item:
            # 落终态：未识别不影响任务状态，也不会永远挂在「待确认」计数里。
            engine.update_item(item['id'], state='skipped', step=detail, message=reason)
        store.event('share_organize', f'分享 STRM 未识别：{row["name"][:60]}（{detail}）。')
    if moved:
        if item:
            engine.update_item(item['id'], state='skipped', step='未识别，已转待确认目录', message=reason)
        store.event('share_organize', f'分享 STRM 未识别：{row["name"][:60]}（{reason}）')


def _wash(engine, job_id, row, org_dir, dest, target_stem, hint, new_facts, policy, wash_on, retiring):
    """按作品、集数和共存组决定洗版；旧条目在新版安全发布后处理。"""
    store, root = engine.store, engine.root
    lib_rel = str(org_dir.relative_to(root)).rstrip('/')
    incumbents = store.db.execute(
        "SELECT * FROM share_strms WHERE revoked=0 AND id<>? AND strm_path LIKE ?",
        (row['id'], lib_rel + '/%')).fetchall()
    if hint['media_type'] == 'tv':
        expected = (hint['season'], hint['episode'], hint['end_episode'])
        incumbents = [old for old in incumbents
                      if episode_range_of(Path(old['strm_path']).stem) == expected]
    if incumbents and (not wash_on or policy['mode']=='skip'):return 'hold'
    if incumbents and policy['mode']=='pending':return 'pending'
    worse = []
    for old in incumbents:
        try:
            old_facts = json.loads(old['facts']) if old['facts'] else facts(old['name'], media_from_filename(old['name']), old['size'] or 0)
        except (ValueError, TypeError):
            old_facts = facts(old['name'], media_from_filename(old['name']), old['size'] or 0)
        try:
            base_policy = {**policy, 'dynamic_groups': 'off'}
            if group_key(new_facts, base_policy) != group_key(old_facts, base_policy):
                continue
            unknown_new = policy['dynamic_groups'] == 'dovi' and new_facts.get('dynamic_range') is None
            unknown_old = policy['dynamic_groups'] == 'dovi' and old_facts.get('dynamic_range') is None
            if not unknown_new and not unknown_old and group_key(new_facts, policy) != group_key(old_facts, policy):
                continue
            if unknown_new:
                result, evidence = 0, [{'rule':'dynamic_group','result':'unknown'}]
            elif unknown_old:
                result, evidence = 1, [{'rule':'dynamic_group','result':'unknown'}]
            else:
                result, evidence = compare(new_facts, old_facts, policy, skip_unknown=True)
            skipped = [item.get('label', item.get('rule')) for item in evidence if item.get('result') == 'unknown']
            if skipped:
                store.event('share_wash', '分享洗版跳过未知项：' + '、'.join(skipped))
        except NeedsReview:
            continue  # 无有效比较规则时不淘汰旧版。
        if result <= 0:
            return 'skip'  # 新版本不优于已有。
        if result > 0:
            worse.append(old)
    if dest.exists() and not any((root / old['strm_path']) == dest for old in worse):
        return 'hold'
    retiring.extend(worse)
    return 'publish'


async def check_alive(engine):
    """Revoke only a proven invalid share whose registered local file is owned."""
    from .internal_delete import remember, recent
    store, root = engine.store, engine.root
    rows = store.db.execute(
        'SELECT id, share_code, receive_code, file_id, strm_path FROM share_strms WHERE revoked=0').fetchall()
    dead, alive, skipped = [], 0, 0
    for row in rows:
        try:
            await engine.cloud.share_url_download(
                row['file_id'], row['share_code'], row['receive_code'], 'StrimKeep/0.6')
            alive += 1
        except CloudError as exc:
            if not share_is_dead(exc):
                skipped += 1
                continue
            # Check the live row under the publication lock after the network
            # wait: a concurrent organiser may have changed or moved it.
            async with engine.publication_gate:
                current = store.db.execute(
                    'SELECT id,share_code,receive_code,file_id,strm_path,revoked FROM share_strms WHERE id=?',
                    (row['id'],)).fetchone()
                fields = ('id', 'share_code', 'receive_code', 'file_id', 'strm_path')
                if not current or current['revoked'] or any(current[k] != row[k] for k in fields):
                    skipped += 1
                    continue
                path = _verified_share_strm(root, current['strm_path'], current['id'])
                if path is None:
                    skipped += 1
                    store.event('share_check', '失效分享的本地文件归属无法确认，已保留并跳过。')
                    continue
                # Remove the STRM and its own sidecars; the directory-level
                # sidecars are cleared only when no other share STRM remains.
                try:
                    remember(store, [current['strm_path']])
                    if current['strm_path'] not in recent(store):
                        skipped += 1
                        continue
                    purge_strm(path, root, store=store)
                except (OSError, RuntimeError):
                    skipped += 1
                    continue
                with store.db:
                    changed = store.db.execute(
                        'UPDATE share_strms SET revoked=1 WHERE id=? AND revoked=0 AND strm_path=?',
                        (row['id'], row['strm_path'])).rowcount
                    if changed == 1:
                        # 死分享的 STRM 已经撤掉，它的媒体信息重试也没有意义。
                        store.db.execute(
                            "DELETE FROM native_media_info_queue WHERE json_extract(target,'$.relative')=?",
                            (current['strm_path'],))
                if changed != 1:
                    skipped += 1
                    continue
                dead.append({'id': row['id'], 'name': '', 'strm_path': row['strm_path']})
        except Exception:
            skipped += 1
            continue
    if dead:
        store.event('share_check', '存活检测：%d 个分享 STRM 失效已清理，%d 个正常，%d 个暂时无法判定已跳过。' % (len(dead), alive, skipped))
    elif skipped:
        store.event('share_check', '存活检测：全部 %d 个暂时无法判定（登录/限流/网络或文件状态变化），未做任何撤销。' % skipped)
    store.set_meta('share_check_last', {'at': time.time(), 'alive': alive,
                                        'dead': len(dead), 'skipped': skipped})
    return {'alive': alive, 'dead': dead, 'dead_count': len(dead), 'skipped': skipped}


