def share_recognition_hint(row):
    """Use an evidenced work directory only when the filename is just an episode.

    New rows retain the original share directories in the registry; legacy
    rows keep their original share-code path and remain readable.
    """
    name = row['name']
    stem = Path(name).stem
    bare_episode = re.match(
        r'(?i)^(?:s\d{1,2}[ ._-]*e\d{1,3}|e(?:p)?[ ._-]?\d{1,4}|第\s*\d{1,4}\s*[集话話])',
        stem) or re.fullmatch(r'\d{1,4}', stem.strip())
    folder = None
    if bare_episode:
        from .media import folder_context
        dirs = _share_source_dirs(row)
        if dirs:
            candidate = '/'.join(dirs)
            context = folder_context(candidate)
            if (context and not _is_share_category(context.get('title'))
                    and (context.get('year') or context.get('tmdb_id'))):
                folder = candidate
    hint = require_work_identity(require_single_episode(parse_name(stem, folder), name))
    if folder and not hint.get('tmdb_id'):
        hint['identity_source'] = 'ancestor_directory'
    return hint


def episode_range_of(stem):
    """文件名里的「季 + 集范围」；解析失败或电影返回 None（不可比，永不淘汰）。"""
