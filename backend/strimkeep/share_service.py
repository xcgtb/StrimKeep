def share_play_path_matches(path, sid):
    """Old URLs and a single encoded filename segment identify the same share."""
    # 只认带存储商前缀的新路径；旧格式在启动时已被迁移。
    return bool(re.fullmatch(r'/play115/share/' + re.escape(str(sid)) + r'(?:/[^/]+)?', path))


def share_play_url(base, sid, name):
    from urllib.parse import quote
    return (base or '').rstrip('/') + '/play115/share/' + str(sid) + '/' + quote(str(name), safe='')


def align_existing_share_urls(store, root):
    """Add a readable filename to verified, registered legacy library outputs.

    Run under the startup instance lock before workers begin. Record pending Emby
    paths before each write so a crash or unavailable Emby can be retried.
    """
    from urllib.parse import urlsplit, urlunsplit, quote, unquote
    root = Path(root).resolve()
    if store.db.execute('SELECT 1 FROM share_wash_intents LIMIT 1').fetchone():
        return 0
    try:
        pending = set(json.loads(store.meta('share_url_refresh_pending') or '[]'))
    except (ValueError, TypeError):
        store.event('share', '分享地址升级队列格式异常，已停止自动处理。')
        return 0
    changed = 0
    rows = store.db.execute("SELECT id,file_id,name,strm_path FROM share_strms WHERE revoked=0 AND strm_path LIKE ?", (LIB_NAME + '/%',)).fetchall()
    for row in rows:
        relative = row['strm_path']
        path = root / relative
        try:
            if not path.resolve().is_relative_to((root / LIB_NAME).resolve()) or path.is_symlink() or not path.is_file() or path.stat().st_size > 4096:
                continue
            content = path.read_text(encoding='utf-8')
            parsed = urlsplit(content.strip())
            prefix = '/play/share/' + row['id']
            if parsed.scheme not in ('http', 'https') or not parsed.netloc:
                continue
            # Repair only the exact filename generated by 0.8.15, never an
            # arbitrary user-provided alias for the same playback identity.
            previous_name = path.stem + Path(row['name']).suffix
            if parsed.path != prefix and not (parsed.path.startswith(prefix + '/') and
                                               unquote(parsed.path[len(prefix)+1:]) == previous_name):
                continue
            extension = Path(row['name']).suffix.lower()
            if extension not in PLAYABLE:
                extension = ''
                records = store.db.execute('SELECT original,plan FROM organize_items WHERE file_id=? ORDER BY id DESC', (row['file_id'],))
                for record in records:
                    try:
                        original, plan = json.loads(record['original']), json.loads(record['plan'])
                        if plan.get('playback_id') != 'share/' + row['id']: continue
                        candidate = Path(original.get('name') or '').suffix.lower()
                        if candidate in PLAYABLE: extension = candidate
                        break
                    except (TypeError, ValueError):
                        continue
            name = path.stem + extension
            url = urlunsplit((parsed.scheme, parsed.netloc, prefix + '/' + quote(name, safe=''), parsed.query, parsed.fragment))
            if url == content.strip(): continue
            pending.add(relative)
            with store.db:
                store.db.execute("INSERT OR REPLACE INTO meta VALUES('share_url_refresh_pending',?)", (json.dumps(sorted(pending), ensure_ascii=False),))
            atomic_write(path, url.encode(), root)
            changed += 1
        except (OSError, UnicodeError, ValueError):
            continue
    if changed:
        store.event('share', '分享 STRM 播放地址补充文件名：%d 个；等待 Emby 刷新。' % changed)
    return changed


def migrate_share_play_paths(store, root):
    """把已生成的分享 STRM 从 /play/share/<sid> 升级成 /play/share/115/<sid>。

    旧路径的路由仍然保留（没迁移的也能播），这里只是让存量文件和新生成的一致，
    并为改过的文件登记 Emby 待刷新。幂等：没有旧前缀时返回 0。
    """
    from urllib.parse import urlsplit, urlunsplit
    root = Path(root).resolve()
    try:
        pending = set(json.loads(store.meta('share_url_refresh_pending') or '[]'))
    except (ValueError, TypeError):
        pending = set()
    changed = 0
    rows = store.db.execute("SELECT id,strm_path FROM share_strms WHERE revoked=0").fetchall()
    for row in rows:
        relative = row['strm_path']
        path = root / relative
        try:
            if (not path.resolve().is_relative_to(root) or path.is_symlink()
                    or not path.is_file() or path.stat().st_size > 4096):
                continue
            content = path.read_text(encoding='utf-8').strip()
            parsed = urlsplit(content)
            new_prefix = '/play115/share/' + row['id']
            for prefix in ('/play/share/' + row['id'], '/play/share/115/' + row['id']):
                if parsed.path == prefix or parsed.path.startswith(prefix + '/'):
                    break
            else:
                continue
            url = urlunsplit((parsed.scheme, parsed.netloc,
                              new_prefix + parsed.path[len(prefix):], parsed.query, parsed.fragment))
            pending.add(relative)
            with store.db:
                store.db.execute("INSERT OR REPLACE INTO meta VALUES('share_url_refresh_pending',?)",
                                 (json.dumps(sorted(pending), ensure_ascii=False),))
            atomic_write(path, url.encode(), root)
            changed += 1
        except (OSError, UnicodeError, ValueError):
            continue
    if changed:
        store.event('share', '分享 STRM 播放地址升级为 /play/share/115/：%d 个；等待 Emby 刷新。' % changed)
    return changed


def prune_missing_share_strms(store, root, min_age=3600):
    """把 STRM 文件已经不在的记录标成撤销，返回清理数量。

    只处理创建超过 min_age 秒的记录：刚生成的条目可能还没落盘完成。
    一级目录都不在时直接放弃本轮（挂载抖动不能当成文件被删）。
    """
    root = Path(root).resolve()
    cutoff = time.time() - min_age
    rows = store.db.execute('SELECT id,strm_path FROM share_strms WHERE revoked=0 AND created<?',
                            (cutoff,)).fetchall()
    stale = []
    for row in rows:
        path = root / row['strm_path']
        try:
            if path.is_file():
                continue
            if not (root / row['strm_path'].split('/')[0]).is_dir():
                return 0
        except OSError:
            return 0
        stale.append(row['id'])
    if stale:
        with store.db:
            store.db.executemany('UPDATE share_strms SET revoked=1 WHERE id=?', [(value,) for value in stale])
        store.event('share', '清理了 %d 条文件已不存在的分享 STRM 记录。' % len(stale))
    return len(stale)


def quality_rank(stem):
    """文件名质量证据（分辨率标签缺失=未知 None）。保留给展示与测试；
    洗版决策已统一走 quality.compare，不再按排名淘汰。"""
    rank = {'2160p': 4, '1080p': 3, '720p': 2, '480p': 1}
    dv = {'dv': 3, 'dovi': 3, 'hdr10+': 2, 'hdr10': 2, 'hdr': 2, 'sdr': 1}
    low = str(stem).lower()
    rq = max((rank[k] for k in rank if k in low), default=0)
    rd = max((dv[k] for k in dv if k in low), default=0)
    return None if rq == 0 else (rq, rd)


